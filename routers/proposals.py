from datetime import datetime
from io import BytesIO

from fastapi import APIRouter, HTTPException
from fastapi.responses import Response
from pydantic import BaseModel, Field
from psycopg.rows import dict_row
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

from database import get_connection, get_document, list_benefits

router = APIRouter(prefix="/api/proposals", tags=["Proposals"])

class SalesDecision(BaseModel):
    decision: str = Field(pattern="^(approve|changes)$")
    comments: str = Field(default="", max_length=5000)
    reviewer: str = Field(default="Sales Reviewer", max_length=150)


def _document_data(document_id: int):
    document = get_document(document_id)
    if not document:
        raise HTTPException(status_code=404, detail="Document not found.")
    benefits = list_benefits(document_id)
    with get_connection() as conn:
        conn.row_factory = dict_row
        option = conn.execute("""
            SELECT id, option_number, option_name
            FROM coverage_options
            WHERE document_id=%s AND is_selected=TRUE
            ORDER BY option_number LIMIT 1
        """, (document_id,)).fetchone()
        if not option:
            raise HTTPException(status_code=409, detail="Select and save a coverage option before generating the proposal.")
        values = conn.execute("""
            SELECT benefit_id, proposed_value
            FROM coverage_option_values WHERE option_id=%s
        """, (option["id"],)).fetchall()
        premium = conn.execute("""
            SELECT base_premium, commission_percentage, commission_amount,
                   total_premium, currency_code
            FROM premium_calculations WHERE option_id=%s
            ORDER BY id DESC LIMIT 1
        """, (option["id"],)).fetchone()
    return document, benefits, option, {str(v["benefit_id"]): v["proposed_value"] for v in values}, premium


def _build_pdf(document, benefits, option, values, premium, version):
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=42, leftMargin=42, topMargin=42, bottomMargin=42)
    styles = getSampleStyleSheet()
    story = [Paragraph("CANOPY", styles["Title"]), Paragraph("Employee Benefit Proposal", styles["Heading2"]), Spacer(1, 10)]
    story.append(Paragraph(f"Client: {document.get('client_name') or '—'}", styles["Normal"]))
    story.append(Paragraph(f"Insurer: {document.get('source_insurer') or '—'}", styles["Normal"]))
    story.append(Paragraph(f"Proposal version: {version}", styles["Normal"]))
    story.append(Paragraph(f"Generated: {datetime.now().strftime('%d %B %Y, %H:%M')}", styles["Normal"]))
    story.append(Spacer(1, 16))
    rows = [["Benefit", "Selected coverage"]]
    for benefit in benefits:
        name = benefit.get("benefit_name") or benefit.get("name") or f"Benefit {benefit.get('id', '')}"
        value = values.get(str(benefit.get("id")), "")
        if value is None or not str(value).strip():
            value = benefit.get("limits") or benefit.get("percentages") or benefit.get("benefit_treatment") or ""
        if str(value).strip().upper() in {"NA", "N/A", "NOT APPLICABLE"}:
            continue
        rows.append([str(name), str(value)])
    table = Table(rows, colWidths=[3.25*inch, 3.35*inch], repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#12352B")),
        ("TEXTCOLOR", (0,0), (-1,0), colors.white),
        ("FONTNAME", (0,0), (-1,0), "Helvetica-Bold"),
        ("GRID", (0,0), (-1,-1), .4, colors.HexColor("#D5E2DA")),
        ("ROWBACKGROUNDS", (0,1), (-1,-1), [colors.white, colors.HexColor("#F4F8F5")]),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("LEFTPADDING", (0,0), (-1,-1), 8), ("RIGHTPADDING", (0,0), (-1,-1), 8),
        ("TOPPADDING", (0,0), (-1,-1), 7), ("BOTTOMPADDING", (0,0), (-1,-1), 7),
    ]))
    story += [Paragraph(f"Selected option: {option['option_name']}", styles["Heading3"]), table, Spacer(1, 14)]
    if premium:
        currency = premium.get("currency_code") or "USD"
        story.append(Paragraph(f"Base premium: {currency} {premium.get('base_premium', 0):,.2f}", styles["Normal"]))
        story.append(Paragraph(f"Commission: {premium.get('commission_percentage', 0):.2f}% ({currency} {premium.get('commission_amount', 0):,.2f})", styles["Normal"]))
        story.append(Paragraph(f"Total premium: {currency} {premium.get('total_premium', 0):,.2f}", styles["Heading3"]))
    story += [Spacer(1, 18), Paragraph("This proposal was generated by the Canopy Benefit Intelligence Platform.", styles["Italic"])]
    doc.build(story)
    return buffer.getvalue()


@router.post("/{document_id}/generate")
def generate_proposal(document_id: int):
    document, benefits, option, values, premium = _document_data(document_id)
    if not benefits:
        raise HTTPException(status_code=409, detail="No extracted benefits are available for this document.")
    if not premium:
        raise HTTPException(status_code=409, detail="Save pricing for the selected option before generating the proposal.")
    with get_connection() as conn:
        conn.row_factory = dict_row
        latest = conn.execute("SELECT COALESCE(MAX(version_number), 0) AS version_number FROM proposal_documents WHERE document_id=%s", (document_id,)).fetchone()
        version_number = int(latest["version_number"]) + 1
        version_label = f"v1.{version_number - 1}"
        pdf_bytes = _build_pdf(document, benefits, option, values, premium, version_label)
        row = conn.execute("""
            INSERT INTO proposal_documents
                (document_id, version_number, version_label, status, pdf_data, file_name, selected_option_id, created_at, updated_at)
            VALUES (%s,%s,%s,'Awaiting Sales Review',%s,%s,%s,NOW(),NOW())
            RETURNING id, version_number, version_label, status, created_at
        """, (document_id, version_number, version_label, pdf_bytes, f"proposal-{document_id}-{version_label}.pdf", option["id"])).fetchone()
        conn.execute("UPDATE proposal_documents SET status='Superseded', updated_at=NOW() WHERE document_id=%s AND id<>%s AND status='Awaiting Sales Review'", (document_id, row["id"]))
    return {"message": "Proposal PDF generated and saved successfully.", "proposal": dict(row), "pdf_url": f"/api/proposals/{document_id}/latest/pdf"}


@router.get("/{document_id}/latest")
def latest_proposal(document_id: int):
    get_document_or_404 = get_document(document_id)
    if not get_document_or_404:
        raise HTTPException(status_code=404, detail="Document not found.")
    with get_connection() as conn:
        conn.row_factory = dict_row
        row = conn.execute("""
            SELECT id, document_id, version_number, version_label, status, file_name,
                   created_at, reviewed_by, reviewed_at, sales_comments
            FROM proposal_documents WHERE document_id=%s
            ORDER BY version_number DESC LIMIT 1
        """, (document_id,)).fetchone()
    if not row:
        raise HTTPException(status_code=404, detail="No generated proposal exists for this document.")
    return dict(row)


@router.get("/{document_id}/latest/pdf")
def latest_proposal_pdf(document_id: int):
    with get_connection() as conn:
        conn.row_factory = dict_row
        row = conn.execute("SELECT pdf_data, file_name FROM proposal_documents WHERE document_id=%s ORDER BY version_number DESC LIMIT 1", (document_id,)).fetchone()
    if not row:
        raise HTTPException(status_code=404, detail="No generated proposal PDF exists.")
    return Response(content=bytes(row["pdf_data"]), media_type="application/pdf", headers={"Content-Disposition": f'inline; filename="{row["file_name"]}"', "Cache-Control": "no-store"})


@router.post("/{document_id}/decision")
def sales_decision(document_id: int, payload: SalesDecision):
    with get_connection() as conn:
        conn.row_factory = dict_row
        proposal = conn.execute("SELECT id, status FROM proposal_documents WHERE document_id=%s ORDER BY version_number DESC LIMIT 1 FOR UPDATE", (document_id,)).fetchone()
        if not proposal:
            raise HTTPException(status_code=404, detail="No proposal exists for this document.")
        if proposal["status"] not in ("Awaiting Sales Review", "Revision Requested"):
            raise HTTPException(status_code=409, detail=f"This proposal cannot be reviewed in its current status: {proposal['status']}.")
        if payload.decision == "changes" and not payload.comments.strip():
            raise HTTPException(status_code=422, detail="Enter revision notes before returning the proposal.")
        status = "Sales Approved" if payload.decision == "approve" else "Revision Requested"
        conn.execute("""
            UPDATE proposal_documents SET status=%s, reviewed_by=%s, reviewed_at=NOW(), sales_comments=%s, updated_at=NOW()
            WHERE id=%s
        """, (status, payload.reviewer.strip(), payload.comments.strip(), proposal["id"]))
    return {"message": "Sales decision saved.", "status": status}
@router.get("/returned")
def get_returned_proposals():
    with get_connection() as conn:
        conn.row_factory = dict_row

        rows = conn.execute("""
            SELECT
                id,
                document_id,
                version_label,
                status,
                reviewed_by,
                reviewed_at,
                sales_comments
            FROM proposal_documents
            WHERE status = 'Revision Requested'
            ORDER BY reviewed_at DESC NULLS LAST
        """).fetchall()

    return [dict(row) for row in rows]